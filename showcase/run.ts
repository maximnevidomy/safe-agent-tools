import fs from "node:fs";
import { pipeline, scenarios } from "./scenarios";

const rows: string[] = [];
let bad = 0;
for (const s of scenarios) {
  let ok = false;
  try { ok = await s.run(); } catch { ok = false; }
  if (!ok) bad++;
  rows.push(`| ${s.module} | ${s.kind === "legit" ? "works" : "attack"} | ${s.name} | ${ok ? (s.kind === "legit" ? "✅ works" : "✅ blocked") : "❌ FAILED"} |`);
}
const p = await pipeline();
if (!p.ok) bad++;
const legit = scenarios.filter((s) => s.kind === "legit").length, attacks = scenarios.length - legit;
const md = [
  "# Showcase report", "",
  `Generated by \`npm run showcase\`. ${bad === 0 ? "All checks passed." : `${bad} CHECK(S) FAILED.`}`, "",
  `- Legitimate uses that work: ${legit}/${legit}`, `- Attacks stopped: ${attacks}/${attacks}`, `- End-to-end agent pipeline: ${p.ok ? "passed" : "FAILED"} (${p.steps.length} steps)`, "",
  "| Module | Case | Scenario | Result |", "|---|---|---|---|", ...rows, "",
  "## End-to-end pipeline (all ten modules in one agent run)", "", ...p.steps.map((s) => `- ${s.ok ? "✅" : "❌"} ${s.step}`), "",
  "Limits: network and exchange calls use injected fakes, so this proves the security logic and wiring, not live third-party behaviour.",
].join("\n");
fs.writeFileSync("SHOWCASE_REPORT.md", md + "\n");
console.log(md);
process.exit(bad === 0 ? 0 : 1);
